    private void btnListarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnListarActionPerformed
        DefaultTableModel dtm=(DefaultTableModel) jtregistro.getModel();
        while(dtm.getRowCount() !=0) dtm.removeRow(0);
        
        for(Usuarios u:nuevoU.listar()){
            Object[] rowData ={
                u.getNombre(),
                u.getGenero(),
                u.getEmail(),
                u.getCodigoUsuario(),
                u.getNombreUsuario(),
                u.getContrasena(),
                u.getRol()
        };
            dtm.addRow(rowData);
        }
    }//GEN-LAST:event_btnListarActionPerformed

