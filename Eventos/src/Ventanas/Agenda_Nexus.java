    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int selectedRow =  jtregistro.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un Usuario");
            return;
        }

        List<Usuarios> listaUsuarios = nuevoU.listar();
        Usuarios e = listaUsuarios.get(selectedRow);

        // Eliminar el encuestador
        nuevoU.quitar(e);

        // Actualizar la tabla
        DefaultTableModel dtm = (DefaultTableModel) jtregistro.getModel();
        dtm.removeRow(selectedRow);

        JOptionPane.showMessageDialog(this, "Usuario eliminado.");
    }//GEN-LAST:event_btnEliminarActionPerformed


